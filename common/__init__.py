"""Общие модули отчётов.

Фильтр ниже стоит здесь, а не в console.py: этот пакет импортирует каждый
отчёт, так что тишина действует и при запуске отчёта напрямую, мимо консоли.
"""
import warnings

# Выгрузки из банковских систем несут выпадающие списки и условное
# форматирование в расширенном блоке x14, который openpyxl не разбирает и
# при чтении выбрасывает, предупреждая об этом в консоль. Входные файлы мы
# только читаем и никогда не сохраняем обратно — терять нечего, а
# предупреждение пугает пользователя на каждом запуске.
warnings.filterwarnings(
    "ignore",
    message=r"(Data Validation|Conditional Formatting) extension is not supported",
    category=UserWarning,
    module=r"openpyxl\.",
)
